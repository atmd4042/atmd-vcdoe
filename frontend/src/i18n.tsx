type Ctx = { lang: Lang; t: (k: keyof typeof dict["ar"]) => string; toggle: () => void; isRTL: boolean };
const LangContext = createContext<Ctx>({ lang: "ar", t: (k) => k as string, toggle: () => {}, isRTL: true });

const KEY = "app_lang";

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>("ar");

  useEffect(() => {
    (async () => {
      const saved = await storage.getItem<Lang>(KEY, "ar");
      if (saved) setLang(saved);
    })();
  }, []);

  const toggle = useCallback(async () => {
    const next: Lang = lang === "ar" ? "en" : "ar";
    setLang(next);
    await storage.setItem(KEY, next);
  }, [lang]);

  const t = useCallback((k: keyof typeof dict["ar"]) => dict[lang][k] ?? (k as string), [lang]);

  return (
    <LangContext.Provider value={{ lang, t, toggle, isRTL: lang === "ar" }}>
      {children}
    </LangContext.Provider>
  );
}

export const useI18n = () => useContext(LangContext);

// Allow RTL globally (Arabic primary). Manual textAlign in components handles direction.
I18nManager.allowRTL(true);
